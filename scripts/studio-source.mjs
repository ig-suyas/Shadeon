// Turns src/studio/core.ts and every studio material (src/shaders/<id>/material.ts)
// into the strings the code export inlines: TypeScript for the React export
// and plain JavaScript for the vanilla export. Generated from the files the
// site itself runs, so copied code and the live preview cannot drift apart.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CORE = resolve(root, "src/studio/core.ts");
const SHADERS = resolve(root, "src/shaders");
export const OUTPUT = resolve(root, "src/export/studio-source.generated.ts");

const toJs = (source) =>
  ts
    .transpileModule(source, {
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.ESNext,
        newLine: ts.NewLineKind.LineFeed,
      },
    })
    .outputText.replace(/^export \{\};?\n?/m, "")
    .trim();

/** Inlined source: no imports of the core, no `export` keywords; the header is optional. */
function inline(file, keepHeader = false) {
  const source = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  return (keepHeader ? source : source.replace(/^\/\*\*[\s\S]*?\*\/\n+/, ""))
    .replace(/^import[\s\S]*?from "@\/studio\/core";\n+/m, "")
    .replace(/^export /gm, "")
    .trim();
}

/** The material's header comment, kept as documentation in the export. */
function header(file) {
  const match = /\/\*\*[\s\S]*?\*\//.exec(readFileSync(file, "utf8").replace(/\r\n/g, "\n"));
  return match ? match[0] : "";
}

export function buildStudioSource() {
  // The core keeps its header: it documents the engine in every copied file.
  const core = inline(CORE, true);
  const materials = {};
  const ids = readdirSync(SHADERS, { withFileTypes: true })
    .filter(
      (entry) => entry.isDirectory() && existsSync(resolve(SHADERS, entry.name, "material.ts")),
    )
    .map((entry) => entry.name)
    .sort();
  for (const id of ids) {
    const file = resolve(SHADERS, id, "material.ts");
    const source = inline(file);
    materials[id] = { doc: header(file), ts: source, js: toJs(source) };
  }
  return [
    "// GENERATED by scripts/studio-source.mjs from src/studio/core.ts and the studio",
    "// materials. Do not edit; it is rewritten on every `npm run dev` and `build`.",
    `export const STUDIO_CORE_TS = ${JSON.stringify(core)};`,
    `export const STUDIO_CORE_JS = ${JSON.stringify(toJs(core))};`,
    "export const STUDIO_MATERIALS: Record<string, { doc: string; ts: string; js: string }> = " +
      `${JSON.stringify(materials, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, buildStudioSource());
  console.log("wrote src/export/studio-source.generated.ts");
}
