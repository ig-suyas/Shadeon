// Rewrites src/shaders/registry.ts, loaders.ts and ids.ts from the shader
// folders on disk, so adding a shader is: create its folder, then run
// `npm run gen:catalog`. Display order is DISPLAY_ORDER below; shaders not
// listed there are appended alphabetically. A folder with `material.ts` is a
// studio shader (multi-pass WebGL2 on src/studio/core.ts); one with
// `fragment.ts` is a single-fragment shader for the runtime.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../src/shaders");

/** Gallery order for the "Featured" sort. Studio shaders first, then the originals. */
const DISPLAY_ORDER = [
  "lodestone",
  "flint-glass",
  "black-hole",
  "fog-veil",
  "event-horizon",
  "ink-bloom",
  "pointer-glow",
  "contour-field",
];

const found = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(resolve(root, entry.name, "meta.ts")))
  .map((entry) => entry.name);

const isStudio = (id) => existsSync(resolve(root, id, "material.ts"));

for (const id of found) {
  for (const file of [isStudio(id) ? "material.ts" : "fragment.ts", "PROVENANCE.md"]) {
    if (!existsSync(resolve(root, id, file))) throw new Error(`${id} is missing ${file}`);
  }
}
const missing = DISPLAY_ORDER.filter((id) => !found.includes(id));
if (missing.length > 0)
  throw new Error(`DISPLAY_ORDER lists unknown shaders: ${missing.join(", ")}`);

const ordered = [...DISPLAY_ORDER, ...found.filter((id) => !DISPLAY_ORDER.includes(id)).sort()];
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());

const registry = `// GENERATED by scripts/sync-catalog.mjs. Do not edit; run \`npm run gen:catalog\`.
import type { ShaderMeta } from "./schema";
${[...ordered]
  .sort()
  .map((id) => `import { meta as ${camel(id)} } from "./${id}/meta";`)
  .join("\n")}

/**
 * The catalog: metadata only. GLSL is loaded per shader through \`loaders.ts\`,
 * so listing pages never pay for fragment source they do not show.
 */
export const shaders: readonly ShaderMeta[] = [
${ordered.map((id) => `  ${camel(id)},`).join("\n")}
];

const byId = new Map(shaders.map((shader) => [shader.id, shader]));

export function getShader(id: string): ShaderMeta | undefined {
  return byId.get(id);
}

export function featuredShaders(): ShaderMeta[] {
  return shaders.filter((shader) => shader.featured);
}
`;

const fragmentLines = ordered
  .filter((id) => !isStudio(id))
  .map((id) => `  "${id}": () => import("./${id}/fragment"),`)
  .join("\n");
const materialLines = ordered
  .filter(isStudio)
  .map((id) => `  "${id}": () => import("./${id}/material"),`)
  .join("\n");

const loaders = `// GENERATED by scripts/sync-catalog.mjs. Do not edit; run \`npm run gen:catalog\`.
import type { StudioMaterial } from "@/studio/core";

/**
 * One dynamic import per shader, so each fragment (or studio material) is its
 * own chunk.
 *
 * This is also the seam for future Pro gating: a Pro shader's loader can fetch
 * its source from an authenticated endpoint instead of a public chunk.
 */
const loaders: Record<string, () => Promise<{ fragment: string }>> = {
${fragmentLines}
};

const materials: Record<string, () => Promise<{ material: StudioMaterial }>> = {
${materialLines}
};

const cache = new Map<string, Promise<string>>();
const materialCache = new Map<string, Promise<StudioMaterial>>();

export function loadFragment(id: string): Promise<string> {
  let pending = cache.get(id);
  if (!pending) {
    const loader = loaders[id];
    pending = loader
      ? loader().then((module) => module.fragment)
      : Promise.reject(new Error(\`Unknown shader "\${id}"\`));
    // A failed load (for example a dropped connection) can be retried later.
    pending.catch(() => cache.delete(id));
    cache.set(id, pending);
  }
  return pending;
}

/** The material of a studio (multi-pass WebGL2) shader. */
export function loadMaterial(id: string): Promise<StudioMaterial> {
  let pending = materialCache.get(id);
  if (!pending) {
    const loader = materials[id];
    pending = loader
      ? loader().then((module) => module.material)
      : Promise.reject(new Error(\`Unknown studio shader "\${id}"\`));
    pending.catch(() => materialCache.delete(id));
    materialCache.set(id, pending);
  }
  return pending;
}

/** Ids of single-fragment shaders. */
export function loaderIds(): string[] {
  return Object.keys(loaders);
}

/** Ids of studio shaders. */
export function materialIds(): string[] {
  return Object.keys(materials);
}
`;

// Just the ids, with no imports: src/proxy.ts reads this to answer unknown
// shader URLs with a real 404 before any rendering starts.
const ids = `// GENERATED by scripts/sync-catalog.mjs. Do not edit; run \`npm run gen:catalog\`.
export const SHADER_IDS: readonly string[] = [
${ordered.map((id) => `  "${id}",`).join("\n")}
];
`;

writeFileSync(resolve(root, "registry.ts"), registry);
writeFileSync(resolve(root, "loaders.ts"), loaders);
writeFileSync(resolve(root, "ids.ts"), ids);
console.log(`catalog: ${ordered.length} shaders`);
