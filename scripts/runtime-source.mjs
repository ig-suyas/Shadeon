// Turns src/engine/runtime.ts into the two strings the code export inlines:
// the TypeScript source (for the React export) and plain JavaScript (for the
// vanilla export). Generated from the file the site itself runs, so copied
// code and the live preview cannot drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(root, "src/engine/runtime.ts");
export const OUTPUT = resolve(root, "src/export/runtime-source.generated.ts");

export function buildRuntimeSource() {
  const source = readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n");
  // Drop the file header comment and `export` keywords: the code is inlined.
  const typescript = source
    .replace(/^\/\*\*[\s\S]*?\*\/\n+/, "")
    .replace(/^export /gm, "")
    .trim();
  const javascript = ts
    .transpileModule(typescript, {
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.ESNext,
        newLine: ts.NewLineKind.LineFeed,
      },
    })
    .outputText.replace(/^export \{\};?\n?/m, "")
    .trim();
  return [
    "// GENERATED by scripts/runtime-source.mjs from src/engine/runtime.ts. Do not edit.",
    `export const RUNTIME_TS = ${JSON.stringify(typescript)};`,
    `export const RUNTIME_JS = ${JSON.stringify(javascript)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTPUT, buildRuntimeSource());
  console.log("wrote src/export/runtime-source.generated.ts");
}
